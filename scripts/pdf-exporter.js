/**
 * WebShield PDF Exporter Module
 * Generates professional, multi-page vector PDF security reports using jsPDF.
 */
(() => {
  async function generateSecurityPdf(scanResult) {
    if (!window.jspdf || !window.jspdf.jsPDF) {
      throw new Error('jsPDF library not loaded.');
    }

    const { jsPDF } = window.jspdf;
    const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

    const pageWidth = 210;
    const pageHeight = 297;
    const margin = 14;
    const contentWidth = pageWidth - margin * 2; // 182mm

    let yPos = margin;
    let pageCount = 1;

    // Severity Colors RGB Map
    const colorMap = {
      CRITICAL: { r: 239, g: 68, b: 68, hex: '#EF4444' },
      HIGH:     { r: 249, g: 115, b: 22, hex: '#F97316' },
      MEDIUM:   { r: 245, g: 158, b: 11, hex: '#F59E0B' },
      LOW:      { r: 59,  g: 130, b: 246, hex: '#3B82F6' },
      INFO:     { r: 100, g: 116, b: 139, hex: '#64748B' }
    };

    // Helper: Check Page Overflow & Add Page
    function checkPageOverflow(neededHeight) {
      if (yPos + neededHeight > pageHeight - 18) {
        doc.addPage();
        pageCount++;
        yPos = 22; // Start below running header
        drawPageDecorations();
      }
    }

    // Helper: Draw Running Headers & Footers
    function drawPageDecorations() {
      // Header Bar
      doc.setDrawColor(226, 232, 240);
      doc.setLineWidth(0.3);
      doc.line(margin, 14, margin + contentWidth, 14);

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184); // Muted gray
      doc.text('WEBSHIELD SECURITY ASSESSMENT REPORT', margin, 11);
      doc.text(scanResult.hostname || 'Target Site', margin + contentWidth, 11, { align: 'right' });

      // Footer Bar
      doc.line(margin, pageHeight - 12, margin + contentWidth, pageHeight - 12);
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text(`Generated by WebShield Scanner Pro | ${new Date(scanResult.timestamp).toLocaleDateString()}`, margin, pageHeight - 7);
      doc.text(`Page ${doc.internal.getNumberOfPages()}`, margin + contentWidth, pageHeight - 7, { align: 'right' });
    }

    // -------------------------------------------------------------
    // PAGE 1: EXECUTIVE BANNER & SUMMARY
    // -------------------------------------------------------------

    // Top Brand Header Card
    doc.setFillColor(15, 23, 42); // Dark Slate #0f172a
    doc.roundedRect(margin, yPos, contentWidth, 38, 3, 3, 'F');

    // Title inside banner
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(18);
    doc.setTextColor(255, 255, 255);
    doc.text('WebShield Vulnerability Report', margin + 8, yPos + 14);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(10);
    doc.setTextColor(148, 163, 184);
    doc.text(`Target URL: ${scanResult.url.substring(0, 55)}${scanResult.url.length > 55 ? '...' : ''}`, margin + 8, yPos + 22);
    doc.text(`Protocol: ${scanResult.protocol.toUpperCase()}  |  Scan Date: ${new Date(scanResult.timestamp).toLocaleString()}`, margin + 8, yPos + 29);

    // Score Circle / Badge inside banner (right side)
    const scoreBoxX = margin + contentWidth - 34;
    const scoreBoxY = yPos + 6;
    doc.setFillColor(30, 41, 59); // Inner dark box
    doc.roundedRect(scoreBoxX, scoreBoxY, 26, 26, 2, 2, 'F');

    let ratingColor = colorMap.INFO;
    if (scanResult.score < 50 || scanResult.counts.CRITICAL > 0) ratingColor = colorMap.CRITICAL;
    else if (scanResult.score < 70 || scanResult.counts.HIGH > 0) ratingColor = colorMap.HIGH;
    else if (scanResult.score < 88 || scanResult.counts.MEDIUM > 0) ratingColor = colorMap.MEDIUM;
    else ratingColor = { r: 16, g: 185, b: 129 }; // Green

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.setTextColor(ratingColor.r, ratingColor.g, ratingColor.b);
    doc.text(String(scanResult.score), scoreBoxX + 13, scoreBoxY + 14, { align: 'center' });

    doc.setFontSize(7);
    doc.setTextColor(148, 163, 184);
    doc.text('/100 SCORE', scoreBoxX + 13, scoreBoxY + 20, { align: 'center' });

    yPos += 46;

    // -------------------------------------------------------------
    // EXECUTIVE SUMMARY STATS TABLE
    // -------------------------------------------------------------
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(15, 23, 42);
    doc.text('Executive Summary & Severity Overview', margin, yPos);
    yPos += 6;

    // Summary Card Box
    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(margin, yPos, contentWidth, 26, 2, 2, 'FD');

    // Rating Label
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(ratingColor.r, ratingColor.g, ratingColor.b);
    doc.text(`SECURITY RATING: ${scanResult.rating}`, margin + 8, yPos + 11);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(71, 85, 105);
    doc.text(`Total Vulnerabilities Identified: ${scanResult.totalIssues}`, margin + 8, yPos + 18);

    // Breakdown Pills
    const severities = ['CRITICAL', 'HIGH', 'MEDIUM', 'LOW', 'INFO'];
    let pillX = margin + 90;
    severities.forEach(sev => {
      const count = scanResult.counts[sev] || 0;
      const c = colorMap[sev];

      doc.setFillColor(c.r, c.g, c.b);
      doc.roundedRect(pillX, yPos + 8, 15, 12, 1, 1, 'F');

      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.setTextColor(255, 255, 255);
      doc.text(String(count), pillX + 7.5, yPos + 14, { align: 'center' });

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(6.5);
      doc.setTextColor(100, 116, 139);
      doc.text(sev, pillX + 7.5, yPos + 23, { align: 'center' });

      pillX += 17.5;
    });

    yPos += 34;

    // -------------------------------------------------------------
    // DETECTED TECHNOLOGY STACK
    // -------------------------------------------------------------
    const techs = scanResult.technologies || [];
    if (techs.length > 0) {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(12);
      doc.setTextColor(15, 23, 42);
      doc.text(`Detected Technology Stack (${techs.length} Identified)`, margin, yPos);
      yPos += 6;

      const techBoxHeight = Math.ceil(techs.length / 2) * 10 + 6;
      checkPageOverflow(techBoxHeight);

      doc.setFillColor(248, 250, 252);
      doc.setDrawColor(226, 232, 240);
      doc.roundedRect(margin, yPos, contentWidth, techBoxHeight, 2, 2, 'FD');

      let col = 0;
      let rowY = yPos + 6;
      techs.forEach((t, i) => {
        const itemX = col === 0 ? margin + 6 : margin + (contentWidth / 2) + 2;
        
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(9);
        doc.setTextColor(15, 23, 42);
        const nameVer = t.version ? `${t.name} (v${t.version})` : t.name;
        doc.text(nameVer, itemX, rowY);

        doc.setFont('helvetica', 'normal');
        doc.setFontSize(7.5);
        doc.setTextColor(2, 132, 199);
        doc.text(` [${t.category}]`, itemX + doc.getTextWidth(nameVer) + 1, rowY);

        if (col === 1 || i === techs.length - 1) {
          col = 0;
          rowY += 9;
        } else {
          col = 1;
        }
      });

      yPos += techBoxHeight + 8;
    }

    // -------------------------------------------------------------
    // DETAILED VULNERABILITIES LISTING
    // -------------------------------------------------------------
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(13);
    doc.setTextColor(15, 23, 42);
    doc.text(`Detailed Vulnerability Inventory (${scanResult.vulnerabilities.length} Findings)`, margin, yPos);
    yPos += 8;

    scanResult.vulnerabilities.forEach((item, index) => {
      const c = colorMap[item.severity] || colorMap.INFO;

      // Estimate height needed for this card
      const descLines = doc.splitTextToSize(`Description: ${item.description}`, contentWidth - 16);
      const impactLines = doc.splitTextToSize(`Security Impact: ${item.impact}`, contentWidth - 16);
      const recLines = doc.splitTextToSize(`Remediation: ${item.recommendation}`, contentWidth - 16);
      const snippetLines = item.elementSnippet ? doc.splitTextToSize(`Evidence: ${item.elementSnippet.replace(/\n/g, ' ')}`, contentWidth - 20) : [];

      const cardHeight = 22 + (descLines.length * 4) + (impactLines.length * 4) + (recLines.length * 4) + (snippetLines.length > 0 ? (snippetLines.length * 3.5 + 8) : 4);

      checkPageOverflow(cardHeight);

      // Card Background
      doc.setFillColor(255, 255, 255);
      doc.setDrawColor(226, 232, 240);
      doc.roundedRect(margin, yPos, contentWidth, cardHeight, 2, 2, 'FD');

      // Left Severity Color Stripe
      doc.setFillColor(c.r, c.g, c.b);
      doc.roundedRect(margin, yPos, 4, cardHeight, 2, 0, 'F');
      doc.rect(margin + 2, yPos, 2, cardHeight, 'F'); // Square right edge of stripe

      // Header: Index & Title
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10.5);
      doc.setTextColor(15, 23, 42);
      const titleText = `${index + 1}. ${item.title}`;
      doc.text(titleText.length > 60 ? titleText.substring(0, 58) + '...' : titleText, margin + 8, yPos + 7);

      // Severity Badge (Top Right of Card)
      doc.setFillColor(c.r, c.g, c.b);
      doc.roundedRect(margin + contentWidth - 26, yPos + 3, 22, 6, 1, 1, 'F');
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(7);
      doc.setTextColor(255, 255, 255);
      doc.text(item.severity, margin + contentWidth - 15, yPos + 7, { align: 'center' });

      // ID & Category Subtitle
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(100, 116, 139);
      doc.text(`ID: ${item.id}  |  Category: ${item.category}`, margin + 8, yPos + 12);

      let innerY = yPos + 18;

      // Description
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8.5);
      doc.setTextColor(51, 65, 85);
      descLines.forEach(line => {
        doc.text(line, margin + 8, innerY);
        innerY += 4;
      });

      // Impact
      doc.setTextColor(185, 28, 28); // Dark Red
      impactLines.forEach(line => {
        doc.text(line, margin + 8, innerY);
        innerY += 4;
      });

      // Remediation
      doc.setTextColor(4, 120, 87); // Dark Green
      recLines.forEach(line => {
        doc.text(line, margin + 8, innerY);
        innerY += 4;
      });

      // Evidence Snippet Box
      if (snippetLines.length > 0) {
        innerY += 1;
        const snippetBoxHeight = snippetLines.length * 3.5 + 4;
        doc.setFillColor(241, 245, 249);
        doc.setDrawColor(203, 213, 225);
        doc.roundedRect(margin + 8, innerY, contentWidth - 16, snippetBoxHeight, 1, 1, 'FD');

        doc.setFont('courier', 'normal');
        doc.setFontSize(7.5);
        doc.setTextColor(30, 41, 59);
        snippetLines.forEach(line => {
          doc.text(line, margin + 11, innerY + 3.5);
          innerY += 3.5;
        });
        innerY += 4;
      }

      yPos += cardHeight + 6;
    });

    // Draw headers/footers on all pages
    const totalPages = doc.internal.getNumberOfPages();
    for (let p = 1; p <= totalPages; p++) {
      doc.setPage(p);
      drawPageDecorations();
    }

    // Return generated PDF Blob & filename
    const safeDomain = (scanResult.hostname || 'website').replace(/[^a-z0-9]/gi, '_');
    const dateStr = new Date(scanResult.timestamp).toISOString().split('T')[0];
    const filename = `WebShield_Security_Report_${safeDomain}_${dateStr}.pdf`;

    return {
      pdfDoc: doc,
      filename,
      blob: doc.output('blob')
    };
  }

  window.WebShieldPdfExporter = { generateSecurityPdf };
})();
